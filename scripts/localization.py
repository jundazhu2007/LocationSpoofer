#!/usr/bin/env python3
"""Localization tool.

The source text (Traditional Chinese) is the key. This script:
  1. scans Sources/ for string literals containing Chinese (skipping comments and l10n:ignore regions);
  2. compares them with Localization/translations.json and reports missing or unused translations;
  3. generates Resources/{zh-Hant,en,ja}.lproj/Localizable.strings.

Usage:
  python3 scripts/localization.py check      only check; exits non-zero when something is missing
  python3 scripts/localization.py generate   check, then write the .strings files
  python3 scripts/localization.py list       print every key
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources"
TABLE = ROOT / "Localization" / "translations.json"
OUT = ROOT / "Resources"
LANGS = ["en", "ja"]
CJK = re.compile(r"[\u4e00-\u9fff]")
LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')

def unescape(s: str) -> str:
    return s.replace('\\"', '"').replace("\\\\", "\\").replace("\\n", "\n")

def scan():
    keys, problems = {}, []
    for path in sorted(SOURCES.rglob("*.swift")):
        if "Demo" in path.parts: continue      # Developer tooling: console messages need no translation
        ignoring = False
        for no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if "l10n:ignore-begin" in line: ignoring = True
            elif "l10n:ignore" in line and "ignore-end" not in line: continue
            if ignoring:
                if "l10n:ignore-end" in line: ignoring = False
                continue
            code = line.split("//")[0] if line.lstrip().startswith("//") else line
            # Strip trailing comments (rough: ignores // inside strings)
            code = re.sub(r'\s//[^"]*$', "", code)
            for m in LITERAL.finditer(code):
                text = m.group(1)
                if not CJK.search(text): continue
                if "\\(" in text:
                    problems.append(f"{path.relative_to(ROOT)}:{no}: Chinese literal with interpolation; use L(\"…%@…\", value) instead: {text[:50]}")
                    continue
                keys.setdefault(unescape(text), []).append(f"{path.relative_to(ROOT)}:{no}")
    return keys, problems

def spec_signature(s: str):
    return sorted(re.sub(r"\d+\$", "", m) for m in re.findall(r"%(?:\d+\$)?[-+ 0#]*\d*(?:\.\d+)?(?:ll|l|h)?[@dfsu]", s))

def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    keys, problems = scan()
    if cmd == "list":
        for k in keys: print(k)
        return 0
    table = json.loads(TABLE.read_text(encoding="utf-8")) if TABLE.exists() else {}

    missing = [k for k in keys if k not in table or any(not table[k].get(l) for l in LANGS)]
    unused = [k for k in table if k not in keys]
    bad_spec = [k for k in keys if k in table and any(table[k].get(l) and spec_signature(table[k][l]) != spec_signature(k) for l in LANGS)]

    for p in problems: print("✗", p)
    for k in missing: print("✗ missing translation:", k.replace("\n", "\\n"))
    for k in bad_spec: print("✗ format specifiers differ from the source:", k)
    for k in unused: print("· unused (no longer in the source):", k)
    print(f"{len(keys)} strings: {len(missing)} missing, {len(bad_spec)} format mismatches, {len(unused)} unused, {len(problems)} interpolation problems")
    ok = not (problems or missing or bad_spec)

    if cmd == "generate" and ok:
        def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        for lang, folder in [("zh-Hant", "zh-Hant"), ("en", "en"), ("ja", "ja")]:
            d = OUT / f"{folder}.lproj"; d.mkdir(parents=True, exist_ok=True)
            lines = ["/* Generated by scripts/localization.py — edit Localization/translations.json instead. */"]
            for k in sorted(keys):
                v = k if lang == "zh-Hant" else table[k][lang]
                lines.append(f'"{esc(k)}" = "{esc(v)}";')
            (d / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote", ", ".join(f"{f}.lproj" for _, f in [("", "zh-Hant"), ("", "en"), ("", "ja")]))
    return 0 if ok else 1

if __name__ == "__main__":
    sys.exit(main())
